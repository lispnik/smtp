#!/usr/bin/env python3
"""Generate src/idna-table.lisp from the Unicode UTS #46 and UCD data files.

Usage: python3 -I tools/gen-idna-table.py IdnaMappingTable.txt \
           DerivedJoiningType.txt > src/idna-table.lisp

The data files are those of the Unicode version SBCL's own character data
uses (15.0.0 for SBCL 2.6), from
  https://www.unicode.org/Public/idna/15.0.0/IdnaMappingTable.txt
  https://www.unicode.org/Public/15.0.0/ucd/extracted/DerivedJoiningType.txt
"""
import re
import sys

# Statuses as processed with UseSTD3ASCIIRules=true and
# Transitional_Processing=false.
VALID, DISALLOWED, IGNORED = -1, -2, -3
JOINING = {'L': 1, 'D': 2, 'R': 3, 'T': 4, 'C': 5}


def data_lines(path):
    with open(path, encoding='utf-8') as f:
        for line in f:
            line = line.split('#', 1)[0].strip()
            if line:
                yield [field.strip() for field in line.split(';')]


def code_range(field):
    lo, _, hi = field.partition('..')
    return int(lo, 16), int(hi or lo, 16)


def version(path):
    with open(path, encoding='utf-8') as f:
        for line in f:
            m = re.match(r'#\s*Version:\s*(\S+)', line) or re.match(r'#\s*\S+-(\d+\.\d+\.\d+)\.txt', line)
            if m:
                return m.group(1)
    return 'unknown'


def mapping_table(path):
    ranges = []                 # (start, end, value), value an int status or a tuple
    for fields in data_lines(path):
        lo, hi = code_range(fields[0])
        status = fields[1]
        if status in ('valid', 'deviation'):
            value = VALID
        elif status == 'ignored':
            value = IGNORED
        elif status == 'mapped':
            value = tuple(int(c, 16) for c in fields[2].split())
        elif status in ('disallowed', 'disallowed_STD3_valid', 'disallowed_STD3_mapped'):
            value = DISALLOWED
        else:
            raise ValueError('unknown status %r' % status)
        ranges.append((lo, hi, value))
    ranges.sort()
    expected = 0
    for lo, hi, _ in ranges:
        if lo != expected:
            raise ValueError('gap or overlap at U+%04X' % lo)
        expected = hi + 1
    if expected != 0x110000:
        raise ValueError('table does not reach U+10FFFF')
    return ranges


def compress(ranges):
    """Merge adjacent ranges with equal values: (start, value) pairs."""
    out = []
    for lo, _, value in ranges:
        if out and out[-1][1] == value:
            continue
        out.append((lo, value))
    return out


def joining_table(path):
    types = {}
    for fields in data_lines(path):
        lo, hi = code_range(fields[0])
        if fields[1] in JOINING:
            for c in range(lo, hi + 1):
                types[c] = JOINING[fields[1]]
    out, previous = [], 0
    for c in range(0x110000):
        t = types.get(c, 0)
        if t != previous or not out and t:
            out.append((c, t))
            previous = t
    if not out or out[0][0] != 0:
        out.insert(0, (0, 0))
    return out


def lisp_vector(name, element_type, numbers, doc):
    body = []
    line = ''
    for n in numbers:
        item = str(n)
        if len(line) + len(item) + 1 > 78:
            body.append(line)
            line = ''
        line += (' ' if line else '') + item
    body.append(line)
    return ('(defparameter %s\n  (coerce (quote (\n%s))\n          (quote (simple-array %s (*))))\n  "%s")\n'
            % (name, '\n'.join(body), element_type, doc))


def main(mapping_path, joining_path):
    entries = compress(mapping_table(mapping_path))
    starts, values, data = [], [], []
    offsets = {}
    for start, value in entries:
        starts.append(start)
        if isinstance(value, tuple):
            if value not in offsets:
                offsets[value] = len(data)
                data.extend(value)
            if len(value) >= 32:
                raise ValueError('mapping too long')
            values.append(offsets[value] * 32 + len(value))
        else:
            values.append(value)
    joining = joining_table(joining_path)
    out = sys.stdout
    out.write(';;; idna-table.lisp\n;;;\n;;; SPDX-License-Identifier: MIT AND Unicode-DFS-2016\n;;;\n'
              ';;; GENERATED by tools/gen-idna-table.py; do not edit.\n'
              ';;; Source: IdnaMappingTable.txt %s and DerivedJoiningType.txt %s, from the\n'
              ';;; Unicode Character Database (https://www.unicode.org/terms_of_use.html).\n\n'
              '(in-package #:smtp)\n\n' % (version(mapping_path), version(joining_path)))
    out.write(lisp_vector('*idna-starts*', '(unsigned-byte 32)', starts,
                          'First code point of each run in the UTS #46 mapping table.'))
    out.write('\n')
    out.write(lisp_vector('*idna-values*', '(signed-byte 32)', values,
                          'Per run: -1 valid, -2 disallowed, -3 ignored, otherwise a mapping as offset * 32 + length into *IDNA-MAPPINGS*.'))
    out.write('\n')
    out.write(lisp_vector('*idna-mappings*', '(unsigned-byte 32)', data,
                          'The code points that mapped characters are replaced by.'))
    out.write('\n')
    out.write(lisp_vector('*joining-starts*', '(unsigned-byte 32)', [s for s, _ in joining],
                          'First code point of each run of equal Joining_Type.'))
    out.write('\n')
    out.write(lisp_vector('*joining-types*', '(unsigned-byte 8)', [t for _, t in joining],
                          'Per run: 0 U (non-joining), 1 L, 2 D, 3 R, 4 T, 5 C.'))


if __name__ == '__main__':
    main(*sys.argv[1:3])
